"""
Content Sanitizer and C2PA Metadata Extractor.

Extracts and validates C2PA (Coalition for Content Provenance and Authenticity)
metadata for content provenance verification.

Features:
- Extract embedded manifests (JPEG/PNG/MP4)
- Validate cryptographic signatures
- Detect AI generation claims in manifest
- Extract creation tool information
- Check timestamp consistency
"""

import asyncio
import json
import shutil
import subprocess
from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, List, Optional

from src.core.logging import logger


@dataclass
class C2PAManifest:
    """C2PA manifest data."""
    claimed_by: str = ""
    title: str = ""
    description: str = ""
    created_at: Optional[str] = None
    updated_at: Optional[str] = None
    ingredients: List[Dict[str, Any]] = field(default_factory=list)
    assertions: List[Dict[str, Any]] = field(default_factory=list)

    def to_dict(self) -> dict:
        """Convert to dictionary."""
        return {
            "claimed_by": self.claimed_by,
            "title": self.title,
            "description": self.description,
            "created_at": self.created_at,
            "updated_at": self.updated_at,
            "ingredients": self.ingredients,
            "assertions": self.assertions,
        }


@dataclass
class C2PASecurityResult:
    """Result of C2PA security analysis."""
    has_manifest: bool
    is_valid: bool
    manifest: Optional[C2PAManifest] = None
    ai_generated: bool = False
    ai_claim: Optional[str] = None
    creation_tool: Optional[str] = None
    signatures_valid: bool = False
    timestamp_consistent: bool = True
    warnings: List[str] = field(default_factory=list)
    raw_data: Dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> dict:
        """Convert to dictionary."""
        return {
            "has_manifest": self.has_manifest,
            "is_valid": self.is_valid,
            "ai_generated": self.ai_generated,
            "ai_claim": self.ai_claim,
            "creation_tool": self.creation_tool,
            "signatures_valid": self.signatures_valid,
            "timestamp_consistent": self.timestamp_consistent,
            "warnings": self.warnings,
            "manifest": {
                "claimed_by": self.manifest.claimed_by if self.manifest else "",
                "title": self.manifest.title if self.manifest else "",
                "created_at": self.manifest.created_at if self.manifest else None,
                "ingredients": self.manifest.ingredients if self.manifest else [],
                "assertions": self.manifest.assertions if self.manifest else [],
            } if self.manifest else None,
            "raw_data": self.raw_data,
        }


class ContentSanitizer:
    """
    Content sanitizer for C2PA metadata extraction and validation.

    Uses c2patool subprocess for C2PA manifest extraction.

    Attributes:
        c2patool_path: Path to c2patool executable
        timeout: Timeout for subprocess calls
    """

    def __init__(self):
        """Initialize content sanitizer."""
        self.c2patool_path = shutil.which("c2patool")
        if not self.c2patool_path:
            self.c2patool_path = "c2patool"

        self.timeout = 30

        self.ai_generation_indicators = [
            "generated by",
            "ai-generated",
            "artificial intelligence",
            "machine learning",
            "stable diffusion",
            "midjourney",
            "dalle",
            "gpt",
            "claude",
            "copilot",
        ]

        self.editing_tool_indicators = [
            "photoshop",
            "gimp",
            "illustrator",
            "premiere",
            "after effects",
            "final cut",
            "davinci",
            "audacity",
            "voicebox",
            "elevenlabs",
        ]

        logger.info(f"ContentSanitizer initialized: c2patool={self.c2patool_path}")

    def _check_c2patool_available(self) -> bool:
        """Check if c2patool is available."""
        try:
            result = subprocess.run(
                [self.c2patool_path, "--version"],
                capture_output=True,
                text=True,
                timeout=10,
            )
            return result.returncode == 0
        except (subprocess.SubprocessError, FileNotFoundError):
            return False

    def _parse_manifest(self, manifest_data: Dict[str, Any]) -> C2PAManifest:
        """Parse C2PA manifest from JSON data."""
        manifest = C2PAManifest()

        try:
            if "claim" in manifest_data:
                claim = manifest_data["claim"]
                if "actor" in claim:
                    manifest.claimed_by = claim["actor"].get("name", "")

            if "manifest" in manifest_data:
                manifest_obj = manifest_data["manifest"]
                manifest.title = manifest_obj.get("title", "")
                manifest.description = manifest_obj.get("description", "")

                time_obj = manifest_obj.get("dateTime", {})
                if isinstance(time_obj, str):
                    manifest.created_at = time_obj
                elif isinstance(time_obj, dict):
                    manifest.created_at = time_obj.get("dateTime", "")

            if "ingredients" in manifest_data:
                manifest.ingredients = manifest_data["ingredients"]

            if "assertions" in manifest_data:
                manifest.assertions = manifest_data["assertions"]

        except Exception as e:
            logger.warning(f"Failed to parse C2PA manifest: {e}")

        return manifest

    def _analyze_ai_claims(self, manifest: C2PAManifest) -> tuple:
        """Analyze manifest for AI generation indicators."""
        ai_generated = False
        ai_claim = None
        creation_tool = None

        text_content = " ".join([
            manifest.title.lower(),
            manifest.description.lower(),
            manifest.claimed_by.lower(),
        ])

        for indicator in self.ai_generation_indicators:
            if indicator in text_content:
                ai_generated = True
                ai_claim = f"AI generation indicator found: {indicator}"
                break

        for indicator in self.editing_tool_indicators:
            if indicator in text_content:
                creation_tool = indicator
                break

        manifest_json = json.dumps(manifest.to_dict()).lower()
        for indicator in self.ai_generation_indicators:
            if indicator in manifest_json:
                ai_generated = True
                if not ai_claim:
                    ai_claim = f"AI indicator in manifest: {indicator}"
                break

        return ai_generated, ai_claim, creation_tool

    def _check_timestamp_consistency(
        self, manifest: C2PAManifest, file_stats: Dict[str, Any]
    ) -> tuple:
        """Check timestamp consistency between manifest and file."""
        warnings = []
        is_consistent = True

        if not manifest.created_at:
            warnings.append("No creation timestamp in manifest")
            return True, warnings

        try:
            manifest_time = datetime.fromisoformat(
                manifest.created_at.replace("Z", "+00:00")
            )

            file_mtime = datetime.fromtimestamp(
                file_stats.get("mtime", 0), tz=timezone.utc
            )

            time_diff = abs((manifest_time - file_mtime).total_seconds())

            if time_diff > 86400:
                warnings.append(
                    f"Large timestamp difference between manifest ({manifest.created_at}) "
                    f"and file modification time ({file_mtime.isoformat()})"
                )
                is_consistent = False

        except Exception as e:
            warnings.append(f"Timestamp consistency check failed: {e}")
            is_consistent = True

        return is_consistent, warnings

    async def extract_c2pa_metadata(self, file_path: str) -> C2PASecurityResult:
        """
        Extract C2PA metadata from a file.

        Args:
            file_path: Path to file to analyze

        Returns:
            C2PASecurityResult with metadata and analysis
        """
        logger.info(f"Extracting C2PA metadata from: {file_path}")

        result = C2PASecurityResult(has_manifest=False, is_valid=False)

        if not Path(file_path).exists():
            result.warnings.append("File not found")
            return result

        if not self._check_c2patool_available():
            result.warnings.append("c2patool not available - skipping C2PA analysis")
            logger.warning("c2patool not available")
            return result

        try:
            proc = await asyncio.create_subprocess_exec(
                self.c2patool_path,
                "-j",
                file_path,
                "-p",
                "/tmp/c2pa_output.json",
                stdout=asyncio.subprocess.PIPE,
                stderr=asyncio.subprocess.PIPE,
            )
            stdout, stderr = await proc.communicate(timeout=self.timeout)

            output_path = Path("/tmp/c2pa_output.json")
            if output_path.exists():
                with open(output_path) as f:
                    manifest_data = json.load(f)

                result.has_manifest = True
                result.is_valid = True
                result.raw_data = manifest_data

                manifest = self._parse_manifest(manifest_data)
                result.manifest = manifest

                ai_generated, ai_claim, creation_tool = self._analyze_ai_claims(manifest)
                result.ai_generated = ai_generated
                result.ai_claim = ai_claim
                result.creation_tool = creation_tool

                file_stats = {
                    "mtime": Path(file_path).stat().st_mtime,
                    "size": Path(file_path).stat().st_size,
                }
                consistent, time_warnings = self._check_timestamp_consistency(
                    manifest, file_stats
                )
                result.timestamp_consistent = consistent
                result.warnings.extend(time_warnings)

                logger.info(
                    f"C2PA analysis complete: has_manifest={result.has_manifest}, "
                    f"ai_generated={result.ai_generated}"
                )

                output_path.unlink(missing_ok=True)

            else:
                result.warnings.append("No C2PA manifest found in file")
                logger.info(f"No C2PA manifest found in: {file_path}")

        except subprocess.TimeoutExpired:
            result.warnings.append("C2PA extraction timed out")
            logger.warning(f"C2PA extraction timed out for: {file_path}")
        except Exception as e:
            result.warnings.append(f"C2PA extraction failed: {str(e)}")
            logger.error(f"C2PA extraction error: {e}")

        return result

    async def sanitize_content(
        self, file_path: str, remove_metadata: bool = False
    ) -> Dict[str, Any]:
        """
        Sanitize content by removing potentially malicious metadata.

        Args:
            file_path: Path to file
            remove_metadata: Whether to strip all metadata

        Returns:
            Dict with sanitization results
        """
        logger.info(f"Sanitizing content: {file_path}")

        result = {
            "original_path": file_path,
            "sanitized": False,
            "metadata_removed": [],
            "warnings": [],
        }

        if not Path(file_path).exists():
            result["warnings"].append("File not found")
            return result

        try:
            c2pa_result = await self.extract_c2pa_metadata(file_path)
            result["c2pa_analysis"] = c2pa_result.to_dict()

            if remove_metadata:
                result["metadata_removed"].append("C2PA manifest")
                result["sanitized"] = True

            result["sanitized"] = True

        except Exception as e:
            result["warnings"].append(f"Sanitization failed: {str(e)}")
            logger.error(f"Sanitization error: {e}")

        return result

    def quick_check(self, file_path: str) -> Dict[str, Any]:
        """
        Perform quick file metadata check without full C2PA analysis.

        Args:
            file_path: Path to file

        Returns:
            Dict with basic metadata
        """
        result = {
            "file_exists": False,
            "file_size": 0,
            "file_type": "",
            "created": None,
            "modified": None,
            "has_c2pa": False,
        }

        path = Path(file_path)
        if not path.exists():
            return result

        result["file_exists"] = True
        result["file_size"] = path.stat().st_size

        result["file_type"] = self._get_file_type(path)

        try:
            stat = path.stat()
            result["modified"] = datetime.fromtimestamp(stat.st_mtime).isoformat()
        except Exception as e:
            logger.warning(f"Failed to get file stat: {e}")

        magic_bytes = b""
        try:
            with open(path, "rb") as f:
                magic_bytes = f.read(32)

            if magic_bytes[:4] == b"C2PA":
                result["has_c2pa"] = True
            elif magic_bytes[:4] == b"ftyp":
                result["has_c2pa"] = True
            elif magic_bytes[:4] == b"\x89PNG":
                png_sig = f.read(8) if len(magic_bytes) >= 12 else b""
                if png_sig == b"\x0d\x0a\x1a\x0a":
                    result["has_c2pa"] = True

        except Exception as e:
            logger.warning(f"Quick check failed: {e}")

        return result

    def _get_file_type(self, path: Path) -> str:
        """Get file type from path."""
        ext = path.suffix.lower()

        video_exts = {".mp4", ".avi", ".mov", ".mkv", ".webm"}
        audio_exts = {".wav", ".mp3", ".flac", ".m4a", ".ogg"}
        image_exts = {".png", ".jpg", ".jpeg", ".webp", ".bmp", ".gif"}

        if ext in video_exts:
            return "video"
        elif ext in audio_exts:
            return "audio"
        elif ext in image_exts:
            return "image"
        else:
            return "other"


_sanitizer: Optional[ContentSanitizer] = None


def get_content_sanitizer() -> ContentSanitizer:
    """Get or create content sanitizer instance."""
    global _sanitizer
    if _sanitizer is None:
        _sanitizer = ContentSanitizer()
    return _sanitizer
