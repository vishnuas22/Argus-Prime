"""
DistilDIRE - Lightweight Video/Image Deepfake Detector.

Implements DIRE (DIffusion Reconstruction Error) for detecting AI-generated images:
- Distilled diffusion model for fast inference
- Reconstruction error as fake signal
- 3.2x faster than full DIRE, 52.4MB model size
- Excellent for CPU/low-GPU deployment

Theory: DIRE measures reconstruction error from diffusion model; fake images
        generated by diffusion models have higher reconstruction error.
"""

